"""Writes src/gen/build.asm with the build date (LS_BUILT), for Help, About. build.bat runs it
on every build. The version number itself is checked in: src/version.asm."""
import datetime
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
gen = os.path.join(ROOT, 'src', 'gen')
os.makedirs(gen, exist_ok=True)
with open(os.path.join(gen, 'build.asm'), 'w', newline='\n') as f:
    f.write('; generated by tools/build_info.py on every build: do not edit\n')
    f.write('LS_BUILT        = "%s"\n' % datetime.date.today().isoformat())
